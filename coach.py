class EssayCoach:
    def __init__(self, library):
        self.library = library
        self.engine = LocalLlama()

    def status(self):
        return self.engine.status()

    def answer(self, mode, user_text):
        task = MODES.get(mode, MODES["Ответить на мой вопрос"])
        references = self.library.context_for(user_text)
        prompt = (
            f"<|im_start|>system\n{SYSTEM_PROMPT}\n\nЗАДАЧА: {task}\n\n"
            f"СПРАВОЧНЫЕ МАТЕРИАЛЫ ИЗ ЛОКАЛЬНОЙ БИБЛИОТЕКИ:\n{references}<|im_end|>\n"
            f"<|im_start|>user\n{user_text}<|im_end|>\n<|im_start|>assistant\n"
        )
        return self.engine.generate(prompt, max_tokens=1300, temperature=0.55, top_p=0.9)
